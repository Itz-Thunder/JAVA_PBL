public class Donor {

    String name;
    String age;
    String gender;
    String bloodGroup;
    String phone;
    String city;

    public Donor(String name, String age, String gender,
                 String bloodGroup, String phone, String city) {

        this.name = name;
        this.age = age;
        this.gender = gender;
        this.bloodGroup = bloodGroup;
        this.phone = phone;
        this.city = city;
    }
}